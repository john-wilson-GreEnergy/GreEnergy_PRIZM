import assert from 'node:assert/strict';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {thermalUnits} from '../server/thermal/thermalModel';
import {projectMobileHvac} from '../../scripts/mobile-hvac';
import {MobileHvac} from './MobileHvac';
import {emptyMetrics} from '../core/fleet/model';
const now=Date.now();
const units=thermalUnits([{ip:'10.0.1.10',arrayIndex:1,segmentLabel:'ES 1',lastSuccessUtc:new Date(now).toISOString(),spaceTemperatureC:25,hvac1:{compressorOn:true,reversingValveOn:false,currentA:0},hvac2:{compressorOn:false,electricHeatOn:false,freezeDetected:true},faultMessages:['FSS fault']}],now);
const data=projectMobileHvac({units},now);
assert.equal(data.units.length,2);assert.equal(data.units[0].readings.space.text,'77.0 °F');assert.equal(data.units[0].readings.current.text,'0.0 A');assert.equal(data.units[0].readings.rpm.text,'Not reported');
assert(!('ip' in data.units[0]));assert(!('commands' in data.units[0]));
assert.deepEqual(data.units[0].faults,[]);assert.deepEqual(data.units[0].controllerAlerts,['FSS fault']);
assert.deepEqual(data.units[1].faults,['Freeze detected']);
const stale=projectMobileHvac({units},now+130000);assert.equal(stale.units[0].quality,'Stale');assert.equal(stale.units[0].readings.space.text,'Stale');
assert.throws(()=>projectMobileHvac({units:[...units,units[0]]}));assert.throws(()=>projectMobileHvac({units:[{...units[0],array:0}]}));
const site={siteId:'test',blockId:'1',stationCode:'TEST',blockIndex:1,name:'Test site',status:'current' as const,lastReceivedAt:null,observedAt:null,ageMs:null,metrics:emptyMetrics(),mobileHvac:data};
const html=renderToStaticMarkup(<MobileHvac site={site}/>);
assert(html.includes('HVAC overhead'));assert(html.includes('View details'));assert(html.includes('faults reported'));assert(html.includes('<b>H1</b>'));assert(!html.includes('title='));assert(!html.includes('Reset'));assert(!html.includes('Setpoint changes'));
assert.equal((html.match(/FSS fault/g)??[]).length,1,'Segment alert appears once, not as two HVAC faults');
assert(html.includes('1 segment alerts'));assert(html.includes('m-hvac-pair'));
console.log('Mobile HVAC canonical projection, Fahrenheit, zero/missing, stale, fault labels and tap targets passed');
