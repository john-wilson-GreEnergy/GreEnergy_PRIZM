import React from 'react';
import assert from 'node:assert/strict';
import {renderToStaticMarkup} from 'react-dom/server';
import {StreamHealthTable} from './SourceStreamHealth';
const html=renderToStaticMarkup(<StreamHealthTable rows={[{name:'unknown',recordCount:0,durationMs:0},{name:'retained',ok:true,stale:true,error:'Timeout',endpoint:'/report.json'},{name:'failed',ok:false,httpStatus:503}]}/>);
assert.match(html,/Unknown/);assert.match(html,/Stale/);assert.match(html,/Failed/);
assert.match(html,/Timeout/);assert.match(html,/503/);assert.match(html,/0 ms/);
assert.match(html,/Not reported/);assert.match(html,/\/report.json/);
const empty=renderToStaticMarkup(<StreamHealthTable rows={[]}/>);
assert.match(empty,/does not indicate that sources are healthy/);
console.log('Source health: unknown, stale, failed, empty, zero readings, endpoints and errors passed');
