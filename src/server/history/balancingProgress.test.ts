import assert from "node:assert/strict";
import * as fs from "node:fs/promises";
import {projectBalancingProgress, BalancingProgressReview} from "./balancingProgress";
import {projectStringTimeline} from "./stringTimelineProjection";
import {OperationalTimeline} from "./operationalTimeline";
const start = Date.now();
const row = {arrayNumber: 1, stringNumber: 2, communicating: true, inRotation: false, sourceDebug: {sourceStatus: "live"},
  minCellVoltageMv: 3250, maxCellVoltageMv: 3270, avgCellVoltageMv: 3260, currentA: 0, balanceTelemetryAvailable: true, balanceMode: "Provided",
  balanceDetails: [{bpIndex: 1, balanceTelemetryPresent: true, state: "Charging", balancingCellGroup: 2, chargeDeadband: 5, dischargeDeadband: 10, providedVoltageTarget: 3260}]};
const sample = projectBalancingProgress(row);
assert.equal(sample.spreadMv, 20); assert.equal(sample.currentA, 0); assert.equal(sample.chargeDeadband, "5 mV");
assert.match(sample.activeCells, /cell 2: Charging, voltage unavailable/); assert(!sample.activeCells.includes("3260 mV"));
assert.equal(projectBalancingProgress({...row, maxCellVoltageMv: 3200}).spreadMv, null);
assert.equal(projectBalancingProgress({...row, balanceDetails: [...row.balanceDetails, {chargeDeadband: 5}]}).chargeDeadband, "Unknown / incomplete");
assert.equal(projectBalancingProgress({...row, balanceDetails: [{...row.balanceDetails[0], state: "Off"}]}).activeBpcs, 0);
const obs = (offset: number, spread = 20) => projectStringTimeline([{...row, maxCellVoltageMv: 3250 + spread, sourceTimestampUtc: new Date(start + offset).toISOString()}], start + offset)[0];
const review = new BalancingProgressReview(start + 120000, 2);
review.add(obs(0)); review.add(obs(60000, 18)); review.add(obs(120000, 15));
let report = review.finish();
assert.equal(report.rows[0].trend, "Spread decreased"); assert.equal(report.rows[0].changeMv, -5); assert.equal(report.adb, "Unknown / stale");
const gap = new BalancingProgressReview(start + 300000, 2);
gap.add(obs(0)); gap.add(obs(300000, 5)); assert.equal(gap.finish().rows[0].changeMv, null);
const changed = new BalancingProgressReview(start + 120000, 2);
changed.add(obs(0)); changed.add(obs(60000)); const settingChanged = obs(120000); settingChanged.balancing!.chargeDeadband = "1 mV"; changed.add(settingChanged);
assert.equal(changed.finish().rows[0].changeMv, null);
const stale = new BalancingProgressReview(start + 500000, 2); stale.add(obs(0)); assert.equal(stale.finish().rows[0].sample, null);
const appReview = new BalancingProgressReview(start + 120000, 2);
appReview.add({...obs(120000), entity: "ems-app:ADB0001:100", stream: "ems-app", scope: "block", array: 0, string: undefined, values: {"Reported enabled": "ENABLED"}});
assert.equal(appReview.finish().adb, "Enabled");
appReview.add({...obs(120001), entity: "ems-app:ADB0001:100", stream: "ems-app", scope: "block", array: 0, string: undefined, quality: "unavailable", values: {}});
assert.equal(appReview.finish().adb, "Unknown / stale");
const unavailable = new BalancingProgressReview(start + 120000, 2); unavailable.add(obs(0)); unavailable.add({...obs(60000), quality: "unavailable"}); unavailable.add(obs(120000)); assert.equal(unavailable.finish().rows[0].changeMv, null);
const directory = await fs.mkdtemp("/tmp/prizm-balancing-progress-");
let now = start;
const store = new OperationalTimeline(directory, {maxBytes: 1000000, reserveBytes: 0}, () => now);
const site = {id: "fixture", label: "Fixture"};
for (const offset of [0, 30000, 60000, 120000]) {now = start + offset; store.ingest({site, observations: [obs(offset, 20 - offset / 60000)]}); await store.flush();}
const stored = await store.query(1, 1, 2);
assert.equal(stored.samples, 3, "Numerical changes do not increase the existing one-minute string cadence");
assert.equal(stored.balancing!.rows[0].changeMv, -2); assert.equal(store.status().error, null);
now += 60000;
const expired = obs(180000); expired.sourceAt = start - 180000;
store.ingest({site, observations: [expired]}); await store.flush();
const staleReport = await store.query(1, 1, 2);
assert.equal(staleReport.balancing!.rows[0].sample, null, "Recorder quarantines stale numeric and settings evidence");
assert.equal(staleReport.balancing!.points.at(-1)!.spreadMv, null);
process.env.PRIZM_BALANCING_PROGRESS_ENABLED = "false";
assert.equal(projectStringTimeline([row], now)[0].balancing, undefined);
assert.equal((await store.query(1, 1, 2)).balancing, undefined, "Rollback works without replacing history or changing controls");
delete process.env.PRIZM_BALANCING_PROGRESS_ENABLED;
await store.close();
console.log("Balancing progress projection, uncertainty, trend resets, storage cadence and rollback passed");
