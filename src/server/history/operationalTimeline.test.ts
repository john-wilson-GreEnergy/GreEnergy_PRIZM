import assert from "node:assert/strict";
import * as fs from "node:fs/promises";
import path from "node:path";
import {OperationalTimeline} from "./operationalTimeline";
import {timelineChanges, type TimelineBatch, type TimelineObservation} from "./operationalTimelineModel";
const root = await fs.mkdtemp("/tmp/prizm-timeline-test-");
let now = 1_790_000_000_000;
const start = now;
const site = {id: "fixture", label: "Fixture"};
function observation(stream: TimelineObservation["stream"], values: TimelineObservation["values"] = {}): TimelineObservation {
  return {array: 1, entity: "1:1", label: "Array 1 · PCS 1", stream, source: stream === "electrical" ? "EMS Modbus" : "SMA_WEB_PROCESS_DATA", sourceAt: now, observedAt: now, quality: "live", values};
}
const storage = new OperationalTimeline(path.join(root, "history"), {maxBytes: 1_000_000, reserveBytes: 0}, () => now);
const ingest = async (observations: TimelineObservation[], identity = site) => {storage.ingest({site: identity, observations}); await storage.flush();};
await ingest([observation("electrical", {kw: 0, dcV: 1300}), observation("pcs-status", {"DC 1": "OPEN"})]);
assert.equal(storage.status().error, null);
const size = storage.status().usedBytes;
await ingest([observation("electrical", {kw: 0, dcV: 1300}), observation("pcs-status", {"DC 1": "OPEN"})]);
assert.equal(storage.status().usedBytes, size, "Repeated source timestamp is not another observation");
now += 10_000;
await ingest([observation("electrical", {kw: 5, dcV: 1301}), observation("pcs-status", {"DC 1": "CLOSED"})]);
let report = await storage.query(1, 1);
assert.equal(report.samples, 4); assert.equal(report.coverage[0].coverage, "0.3%");
assert(report.events.some(event => event.message === "DC 1: OPEN → CLOSED"));
assert(report.events.some(event => event.message === "Observed status: DC 1: OPEN"), "Record the initial state without inventing a transition");
assert.equal(report.points[0].kw, 5, "Chart retains the last observation of a minute, not a fabricated average");
now += 60_000;
const stale = observation("electrical", {kw: 999}); stale.sourceAt = start;
await ingest([stale]);
report = await storage.query(1, 1);
assert.equal(report.points.at(-1)?.kw, null, "Old samples cannot be shown as fresh readings");
assert(report.events.some(event => event.message.includes("telemetry unavailable")));
assert(!report.events.some(event => event.message.includes("999")));
await assert.rejects(storage.query(1, 48)); await assert.rejects(storage.query(-1, 1));
const beforeDisabled = storage.status().usedBytes;
process.env.PRIZM_OPERATIONAL_TIMELINE_ENABLED = "false";
await ingest([observation("electrical", {kw: 6})]); assert.equal(storage.status().usedBytes, beforeDisabled);
await assert.rejects(storage.query(1, 1), /disabled/);
delete process.env.PRIZM_OPERATIONAL_TIMELINE_ENABLED;
now += 10_000;
await ingest([observation("electrical", {kw: 7})], {id: "other-site", label: "Other site"});
report = await storage.query(1, 1); assert.equal(report.samples, 1); assert.equal(report.site, "Other site");
assert.equal(report.coverage[0].coverage, "0.0%");
const competitor = new OperationalTimeline(path.join(root, "history"), {maxBytes: 1_000_000, reserveBytes: 0}, () => now);
competitor.ingest({site, observations: [observation("electrical")]}); await competitor.flush();
assert.match(competitor.status().error || "", /already has a writer/);
await storage.close();
const reopened = new OperationalTimeline(path.join(root, "history"), {maxBytes: 1_000_000, reserveBytes: 0}, () => now);
reopened.ingest({site, observations: []}); await reopened.flush();
assert.equal((await reopened.query(1, 1)).samples, 5, "Persisted evidence survives restart");
now += 8 * 24 * 3_600_000;
reopened.ingest({site, observations: [observation("electrical", {kw: 1})]}); await reopened.flush();
assert.equal((await reopened.query(1, 1)).samples, 1, "Expired owned records are removed");
await reopened.close();
const capped = new OperationalTimeline(path.join(root, "capped"), {maxBytes: 10, reserveBytes: 0}, () => now);
capped.ingest({site, observations: [observation("electrical")]}); await capped.flush();
assert.match(capped.status().error || "", /storage cap/); assert.equal(capped.status().usedBytes, 0); await capped.close();
const unownedDir = path.join(root, "unowned"); await fs.mkdir(unownedDir); await fs.writeFile(path.join(unownedDir, "user.txt"), "keep");
const unowned = new OperationalTimeline(unownedDir, {maxBytes: 1000, reserveBytes: 0}, () => now);
unowned.ingest({site, observations: [observation("electrical")]}); await unowned.flush();
assert.match(unowned.status().error || "", /unmarked/); assert.equal(await fs.readFile(path.join(unownedDir, "user.txt"), "utf8"), "keep");
const old = observation("pcs-status", {"DC 1": "OPEN"}); now += 130_000;
assert.match(timelineChanges(old, observation("pcs-status", {"DC 1": "CLOSED"}))[0].message, /intervening states unknown/);
const stringStore = new OperationalTimeline(path.join(root, "strings"), {maxBytes: 1_000_000, reserveBytes: 0}, () => now);
const recordString = async (rotation = "IN") => {
  stringStore.ingest({site, observations: [{...observation("string-state", {Rotation: rotation}), entity: "string:1:2", string: 2, label: "Array 1 · String 2"}]});
  await stringStore.flush();
};
await recordString();
const initialStringBytes = stringStore.status().usedBytes;
now += 30_000; await recordString();
assert.equal(stringStore.status().usedBytes, initialStringBytes, "Unchanged strings are not written at PCS cadence");
now += 30_000; await recordString();
const heartbeatBytes = stringStore.status().usedBytes;
assert(heartbeatBytes > initialStringBytes, "Unchanged strings retain a one-minute coverage heartbeat");
now += 1_000; await recordString("OUT");
assert(stringStore.status().usedBytes > heartbeatBytes, "Observed transitions are recorded without waiting another minute");
const stringReport = await stringStore.query(1, 1, 2);
assert.equal(stringReport.samples, 3);
assert(stringReport.events.some(event => event.message === "Rotation: IN → OUT"));
await stringStore.close();
console.log("Timeline persistence, freshness, quality, coverage, site isolation, ownership, limits and rollback passed");
