import assert from "node:assert/strict";
import * as fs from "node:fs/promises";
import {OperationalTimeline} from "./operationalTimeline";
import {beginTimelineCommand} from "./commandTimeline";
import {projectStringTimeline} from "./stringTimelineProjection";
const root = await fs.mkdtemp("/tmp/prizm-command-timeline-");
const base = "http://10.0.0.3:8080/turtle";
const site = {id: JSON.stringify(["Fixture", 1, base]), label: "Fixture"};
let now = Date.now();
const storage = new OperationalTimeline(root, {maxBytes: 10_000_000, reserveBytes: 0}, () => now);
const strings = [1, 2].map(string => ({arrayNumber: 1, stringNumber: string, positiveContactorClosed: false, negativeContactorClosed: false,
  inRotation: false, contactorsCloseExpected: false, communicating: true, sourceTimestampUtc: new Date(now).toISOString(), sourceDebug: {sourceStatus: "live"}}));
storage.ingest({site, observations: projectStringTimeline(strings, now)});
// Command entries must queue even while the first telemetry write owns the writer.
const command = beginTimelineCommand(base, {array: 1, string: 2}, "Balancing AVG; charge deadband 5 mV; discharge deadband 5 mV", storage);
command.result({accepted: true, readbackConfirmed: false});
const arrayCommand = beginTimelineCommand(base, {array: 1, allStrings: true}, "Contactors OPEN", storage);
arrayCommand.result({accepted: false, readbackConfirmed: null});
await storage.flush(); now = Date.now() + 100;
let report = await storage.query(1, 1, 2);
assert.equal(report.events.filter(e => e.kind === "command").length, 4);
assert.deepEqual(report.strings, [1, 2]);
assert(report.events.every(e => e.string == null || e.string === 2));
assert(report.events.some(e => e.message.includes("readback: not confirmed")));
assert(report.events.some(e => e.label === "Array 1 · All strings"));
assert.equal(new Set(report.events.filter(e => e.kind === "command").map(e => e.commandId)).size, 2);
assert.equal(report.coverage.length, 1, "Commands must not count as telemetry coverage");
assert.equal(storage.status().droppedCommands, 0);
await assert.rejects(storage.query(1, 1, 0), /Invalid string/);
const newSite = {id: JSON.stringify(["Other", 1, "http://10.0.0.4:8080/turtle"]), label: "Other"};
storage.ingest({site: newSite, observations: []}); await storage.flush();
command.persistence("changed"); await storage.flush();
assert.equal((await storage.query(1, 1)).events.length, 0, "Late results stay with the command's original site");
storage.ingest({site, observations: []}); await storage.flush(); now = Date.now() + 200;
assert((await storage.query(1, 1, 2)).events.some(e => e.message.includes("LATER SETTINGS CHECK — changed")));
beginTimelineCommand("http://wrong-site:8080/turtle", {array: 1, string: 2}, "Contactors OPEN", storage).result({accepted: true});
assert.equal(storage.status().droppedCommands, 2, "Unresolved site identity is counted, never attributed to another site");
process.env.PRIZM_OPERATIONAL_TIMELINE_ENABLED = "false";
const bytes = storage.status().usedBytes;
beginTimelineCommand(base, {array: 1, string: 2}, "Contactors CLOSE", storage).result({accepted: true});
await storage.flush(); assert.equal(storage.status().usedBytes, bytes);
delete process.env.PRIZM_OPERATIONAL_TIMELINE_ENABLED;
await storage.close();
console.log("Command queue, result semantics, target filter, array scope, late site attribution and rollback passed (no device commands)");
