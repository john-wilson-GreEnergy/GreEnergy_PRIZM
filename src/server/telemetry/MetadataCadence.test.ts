import assert from 'node:assert/strict';
import {MetadataCadence} from './MetadataCadence';
let now=1000, reads=0, value=0;
const gate=new MetadataCadence(60000,()=>now);
const read=async()=>++reads, apply=(n:number)=>{value=n;};
await gate.run('ss3','ipMap',read,apply);
now+=1000; await gate.run('ss3','ipMap',read,apply);
assert.equal(reads,1);assert.equal(value,1);
now+=60000;await gate.run('ss3','ipMap',read,apply);assert.equal(reads,2);
await gate.run('ss4','ipMap',read,apply);assert.equal(reads,3,'same IP on a different site must acquire');
gate.clear();await gate.run('ss4','ipMap',read,apply);assert.equal(reads,4,'explicit invalidation');
await assert.rejects(gate.run('ss4','stringIPMap',async()=>{throw Error('offline');},apply));
await gate.run('ss4','stringIPMap',read,apply);assert.equal(value,5,'failed requests must not suppress recovery');
let release!:(n:number)=>void;
gate.clear();
const slow=gate.run('ss4','ipMap',()=>new Promise<number>(r=>{release=r;}),apply);
await Promise.resolve();
const coalesced=gate.run('ss4','ipMap',async()=>{throw Error('duplicate');},apply);
gate.clear();release(99);await Promise.all([slow,coalesced]);assert.equal(value,5,'old-site completion must not publish');
await gate.run('ss4','ipMap',read,apply);now-=1000;await gate.run('ss4','ipMap',read,apply);assert.equal(value,7,'clock reversal retries');
const disabled=new MetadataCadence();await disabled.run('x','ipMap',read,apply);await disabled.run('x','ipMap',read,apply);assert.equal(value,9,'zero restores per-cycle acquisition');
for(const n of [-1,NaN,Infinity,300001])assert.throws(()=>new MetadataCadence(n));
console.log('Metadata cadence, invalidation, isolation and rollback tests passed');
