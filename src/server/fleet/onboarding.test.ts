import assert from 'node:assert/strict';
import {mkdtemp,writeFile,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {manageFleetAccount,listFleetAccounts} from './accountManagement';
import {hashLocalPassword,readAccounts,parseAccounts} from '../security/localAccounts';
import {LocalSessions} from '../security/localSessions';
import {passwordSetup} from './passwordSetup';
import {parseAdminAction} from './adminRoutes';
const directory=await mkdtemp(path.join(tmpdir(),'prizm-onboarding-')),file=path.join(directory,'accounts.json');
const site={siteId:'one',blockId:'b1',stationCode:'LAB',blockIndex:1,name:'Fixture site'};
const admin={id:'admin',email:'admin@example.test',disabled:false,version:1,fleetAdmin:true,password:await hashLocalPassword('Fixture admin password'),grants:[]};
await writeFile(file,JSON.stringify([admin]),{mode:0o600});
const actor={id:'admin',version:1},email='tech@example.test';
const invite=await manageFleetAccount(file,[site],{kind:'invite',email,siteIds:['one'],workspaceIds:[],remoteAccess:true},actor);
assert(invite.setupToken);assert(invite.pendingSetup);assert(invite.remoteAccess);
const accounts=await readAccounts(file),account=accounts.find(a=>a.email===email)!;
assert(!JSON.stringify(accounts).includes(invite.setupToken));assert(!JSON.stringify(await listFleetAccounts(file)).includes('digest'));
assert.equal(account.grants.length,1);assert.equal(account.grants[0].capability,'telemetry.view');
const sessions=new LocalSessions(()=>readAccounts(file));
await assert.rejects(sessions.login(email,'unknown','fixture'));
const complete=passwordSetup(file,[site],async()=>{});
await assert.rejects(complete({email,token:invite.setupToken,password:'New private fixture password'},'other@example.test'));
await assert.rejects(complete({email,token:'x'.repeat(43),password:'New private fixture password'}));
await complete({email,token:invite.setupToken,password:'New private fixture password'},email);
await assert.rejects(complete({email,token:invite.setupToken,password:'Another fixture password'}));
const session=await sessions.login(email,'New private fixture password','fixture');
const reset=await manageFleetAccount(file,[site],{kind:'setup',email},actor);
await assert.rejects(sessions.authenticate(session.token));
await assert.rejects(sessions.login(email,'New private fixture password','fixture'));
const before=(await readAccounts(file));before.find(a=>a.email===email)!.passwordSetup!.expiresAt=1;
await writeFile(file,JSON.stringify(before),{mode:0o600});
await assert.rejects(complete({email,token:reset.setupToken,password:'New private fixture password'}));
const second=await manageFleetAccount(file,[site],{kind:'setup',email},actor);
await manageFleetAccount(file,[site],{kind:'disable',email},actor);
await assert.rejects(complete({email,token:second.setupToken,password:'New private fixture password'}));
await assert.rejects(manageFleetAccount(file,[site],{kind:'setup',email:admin.email},actor));
assert.throws(()=>parseAccounts([{...admin,remoteAccess:'yes'}]));
assert.throws(()=>parseAccounts([{...admin,passwordSetup:{digest:'a'.repeat(64),expiresAt:Date.now()}}]));
assert.equal(parseAdminAction({kind:'invite',email,siteIds:['one'],workspaceIds:[],remoteAccess:true,confirmationPassword:'private'},new Set()).action.kind,'invite');
assert.throws(()=>parseAdminAction({kind:'redeem',email,token:'x',password:'x',confirmationPassword:'private'},new Set()));
assert(!(await readFile(file,'utf8')).includes('New private fixture password'));
const adminBefore=(await readAccounts(file)).find(a=>a.email===admin.email)!;
await assert.rejects(manageFleetAccount(file,[site],{kind:'remote',email:admin.email,remoteAccess:true},actor),/server console/);
await manageFleetAccount(file,[site],{kind:'remote',email:admin.email,remoteAccess:true});
const adminAfter=(await readAccounts(file)).find(a=>a.email===admin.email)!;
assert.deepEqual(adminAfter,{...adminBefore,version:adminBefore.version+1,remoteAccess:true});
assert.throws(()=>parseAdminAction({kind:'remote',email:admin.email,remoteAccess:true,confirmationPassword:'private'},new Set()));
