import assert from 'node:assert/strict';
import {mkdtemp, readFile, writeFile, chmod, rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {manageFleetAccount, listFleetAccounts} from './accountManagement';
import {readAccounts, verifyLocalPassword} from '../security/localAccounts';
import {LocalSessions} from '../security/localSessions';
const directory = await mkdtemp(path.join(os.tmpdir(), 'prizm-fleet-accounts-'));
const file = path.join(directory, 'accounts.json');
const sites = [3, 4].map(n => ({siteId: 'ss' + n, stationCode: 'LAB' + n, blockId: '1', blockIndex: 1, name: 'Synthetic site ' + n}));
const password = 'abc123';
try {
  await assert.rejects(manageFleetAccount(file,sites,{kind:'add',email:'short@example.invalid',password:'abc12',siteIds:['ss3']}),/6 characters/);
  await manageFleetAccount(file, sites, {kind: 'add', email: 'AdminCreated@example.invalid', password, siteIds: ['ss3', 'ss4']});
  const accounts = await readAccounts(file);
  assert.equal(accounts.length, 1); assert.equal(accounts[0].email, 'admincreated@example.invalid');
  assert.equal(await verifyLocalPassword(password, accounts[0].password), true);
  assert.ok(accounts[0].grants.every(g => g.capability === 'telemetry.view'));
  assert.equal((await readFile(file, 'utf8')).includes(password), false);
  assert.equal(JSON.stringify(await listFleetAccounts(file)).includes('digest'), false);
  const sessions = new LocalSessions(() => readAccounts(file));
  const login = await sessions.login(accounts[0].email, password, 'fixture');
  await manageFleetAccount(file, sites, {kind: 'access', email: accounts[0].email, siteIds: ['ss4']});
  await assert.rejects(sessions.authenticate(login.token));
  assert.deepEqual((await listFleetAccounts(file))[0].sites, ['ss4']);
  await assert.rejects(manageFleetAccount(file,sites,{kind:'workspace',email:accounts[0].email,siteIds:['ss3']}),/existing site telemetry/);
  await manageFleetAccount(file,sites,{kind:'workspace',email:accounts[0].email,siteIds:['ss4']});
  assert.deepEqual((await listFleetAccounts(file))[0].workspaces,['ss4']);
  const fullSession=await sessions.login(accounts[0].email,password,'fixture');
  await manageFleetAccount(file,sites,{kind:'workspace',email:accounts[0].email,siteIds:[]});
  await assert.rejects(sessions.authenticate(fullSession.token));
  assert.deepEqual((await listFleetAccounts(file))[0].workspaces,[]);
  await manageFleetAccount(file, sites, {kind: 'disable', email: accounts[0].email});
  await assert.rejects(new LocalSessions(() => readAccounts(file)).login(accounts[0].email, password, 'fixture'));
  await manageFleetAccount(file, sites, {kind: 'enable', email: accounts[0].email});
  await manageFleetAccount(file, sites, {kind: 'password', email: accounts[0].email, password: password + ' changed'});
  const changed = (await readAccounts(file))[0];
  assert.equal(await verifyLocalPassword(password, changed.password), false);
  assert.equal(await verifyLocalPassword(password + ' changed', changed.password), true);
  const before = await readFile(file, 'utf8');
  await assert.rejects(manageFleetAccount(file, sites, {kind: 'add', email: accounts[0].email, password, siteIds: ['ss3']}));
  await assert.rejects(manageFleetAccount(file, sites, {kind: 'access', email: accounts[0].email, siteIds: ['unknown']}));
  await assert.rejects(manageFleetAccount(file, sites, {kind: 'access', email: accounts[0].email, siteIds: []}));
  await writeFile(path.join(directory, 'provision.lock'), '', {mode: 0o600});
  await assert.rejects(manageFleetAccount(file, sites, {kind: 'disable', email: accounts[0].email}), /EEXIST/);
  await rm(path.join(directory, 'provision.lock'));
  await chmod(directory, 0o755);
  await assert.rejects(manageFleetAccount(file, sites, {kind: 'disable', email: accounts[0].email}), /private/);
  await chmod(directory, 0o700);
  assert.equal(await readFile(file, 'utf8'), before, 'Rejected edits preserve the store');
  console.log('Fleet account admin: salted hashes, multi-site grants, revocation, disable/enable/reset, locking and private storage passed');
} finally { await rm(directory, {recursive: true, force: true}); }
