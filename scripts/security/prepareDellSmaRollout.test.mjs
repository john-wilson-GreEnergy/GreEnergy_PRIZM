import assert from 'node:assert/strict';
import {namespaceMatches,verifiedTarget,enrollmentArrays,inspectEnrollment,validatePreparedManifest,validateSavedEnrollment} from './prepareDellSmaRollout.mjs';
const host={ino:1,dev:9},ss4={ino:2,dev:9};
assert(namespaceMatches('SS3',host,host,null));
assert(!namespaceMatches('SS3',ss4,host,null));
assert(namespaceMatches('SS4',ss4,host,ss4));
assert(!namespaceMatches('SS4',host,host,ss4));
const pin=Array(32).fill('AB').join(':');
const target={array:2,host:'10.0.2.118',deviceId:'12345',fingerprint256:pin,userLevel:0};
const observed={status:200,deviceId:'12345',fingerprint256:pin};
assert.deepEqual(verifiedTarget('SS3',2,target,observed),target);
assert.deepEqual(verifiedTarget('SS4',2,target,{...observed,deviceId:null}),target);
assert.throws(()=>verifiedTarget('SS3',2,target,{...observed,deviceId:null}));
assert.throws(()=>verifiedTarget('SS4',2,target,{...observed,deviceId:'wrong'}));
assert.throws(()=>verifiedTarget('SS3',2,target,{...observed,fingerprint256:Array(32).fill('CD').join(':')}));
assert.throws(()=>verifiedTarget('SS3',2,target,{...observed,status:503}));
assert.throws(()=>verifiedTarget('SS4',1,null,observed));
assert.throws(()=>verifiedTarget('SS4',4,null,{...observed,deviceId:null}));
const newTarget=verifiedTarget('SS4',4,null,observed);
assert.equal(newTarget.host,'10.0.4.118');assert.equal(newTarget.userLevel,0);
assert(!Object.hasOwn(newTarget,'password'));
assert.deepEqual(enrollmentArrays('SS3'),[2,3,4,5,6,7,8]);
assert.deepEqual(enrollmentArrays('SS4'),[1,2,3,4,5,6,7]);
assert.throws(()=>enrollmentArrays('other'));
for(const site of ['SS3','SS4']){
  const targets=[1,2,3,4,5,6,7,8].filter(a=>site!=='SS4'||a!==4).map(array=>({...target,array,host:`10.0.${array}.118`,deviceId:String(10000+array)}));
  const called=[];
  const result=await inspectEnrollment(site,{targets},async array=>{called.push(array);return {...observed,deviceId:String(10000+array)};});
  assert.deepEqual(called,enrollmentArrays(site),'Offline inverters must not receive any request');
  assert.deepEqual(result.targets.map(t=>t.array),enrollmentArrays(site));
  assert.equal(result.targets.length,7);
  const prepared={version:1,stationCode:site==='SS3'?'BHE0020':'BHE0021',blockCode:'B1',targets:result.targets};
  assert.equal(validatePreparedManifest(site,prepared),prepared);
  assert.throws(()=>validatePreparedManifest(site,{...prepared,targets:prepared.targets.map(t=>({...t,password:'must-not-be-public'}))}));
  assert.throws(()=>validatePreparedManifest(site,{...prepared,stationCode:'WRONG'}));
  assert.throws(()=>validatePreparedManifest(site,{...prepared,targets:prepared.targets.slice(1)}));
  await assert.rejects(inspectEnrollment(site,{targets},async()=>({...observed,status:'unavailable'})),'An unexpected unavailable inverter must still block preparation');
}
