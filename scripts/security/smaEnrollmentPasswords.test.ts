import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
import {collectSmaPasswords} from './smaEnrollmentPasswords';
import {sealConfig,openConfig,type SmaStreamConfig} from '../../src/server/telemetry/sma/streamConfig';
const config:SmaStreamConfig={version:1,stationCode:'BHE0021',blockCode:'B1',targets:[1,2,3,4,5,6,7].map(array=>({array,host:`10.0.${array}.118`,deviceId:String(10000+array),fingerprint256:Array(32).fill('AB').join(':'),userLevel:0,password:'validation-only'}))};
const labels:string[]=[];
const collected=await collectSmaPasswords(config,true,async label=>{labels.push(label);return 'test-only-shared-password';});
assert.equal(labels.length,2,'Exactly one entry and one confirmation per site');
assert(labels[0].includes('BHE0021/B1 shared User'));
assert(collected.targets.every(t=>t.password==='test-only-shared-password'));
assert(config.targets.every(t=>t.password==='validation-only'),'Do not mutate source configuration');
const key=randomBytes(32),sealed=sealConfig(collected,key);
assert(!sealed.includes('test-only-shared-password'));assert.deepEqual(openConfig(sealed,key),collected);
let calls=0;
await assert.rejects(collectSmaPasswords(config,true,async()=>++calls===1?'first':'different'));
assert.equal(calls,2);
await assert.rejects(collectSmaPasswords(config,true,async()=>''));
await assert.rejects(collectSmaPasswords(config,true,async()=>'x'.repeat(257)));
calls=0;
await assert.rejects(collectSmaPasswords({...config,targets:config.targets.map((t,i)=>({...t,userLevel:i===0?1:0}))},true,async()=>{calls++;return 'test';}));
assert.equal(calls,0,'Never silently share across login roles');
const individual=await collectSmaPasswords(config,false,async()=>String(Math.floor(calls++/2)));
assert.equal(calls,14);assert.deepEqual(individual.targets.map(t=>t.password),['0','1','2','3','4','5','6']);
const other=await collectSmaPasswords({...config,stationCode:'BHE0020'},true,async()=> 'different-site-test-password');
assert(other.targets.every(t=>t.password==='different-site-test-password'));
assert(collected.targets.every(t=>t.password==='test-only-shared-password'),'No cross-site credential reuse');
const installerLabels:string[]=[];
const installer=await collectSmaPasswords({...config,targets:config.targets.map(t=>({...t,userLevel:1}))},true,async label=>{installerLabels.push(label);return 'installer-fixture-only';});
assert.equal(installerLabels.length,2);assert(installerLabels[0].includes('shared Installer'));
assert(installer.targets.every(t=>t.userLevel===1&&t.password==='installer-fixture-only'));
assert.deepEqual(openConfig(sealConfig(installer,key),key),installer);
console.log('PASS shared-site entry/confirmation, role isolation, per-device compatibility, input immutability, validation and encrypted round-trip');
